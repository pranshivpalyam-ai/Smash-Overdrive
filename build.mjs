#!/usr/bin/env node
/**
 * build.mjs — pack the whole game into ONE self-contained HTML file.
 *
 *     node build.mjs                 → dist/SmashOverdrive.html  and  dist/web/
 *     node build.mjs --online        → single file that loads Three from the CDN instead
 *
 * The game sources are not modified. Two outputs:
 *
 *   dist/SmashOverdrive.html  ONE file. Every module under js/ is embedded as a
 *       data: URL and wired up through an import map, so the browser's real
 *       ES-module loader runs the untouched code. Three.js is embedded the same
 *       way (downloaded once into dist/vendor/), so the file plays offline from
 *       a double-click, a USB stick, OneDrive, email, or any static host.
 *
 *   dist/web/                 A plain static website: index.html with the CSS
 *       inlined plus a copy of js/ in which `from 'three'` points straight at
 *       the pinned CDN build, so no import map is needed. Upload the folder to
 *       any static host (GitHub Pages, Netlify, itch.io, a school web space).
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, relative, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const online = process.argv.includes('--online');
const THREE_VERSION = '0.160.0';
const THREE_CDN = `https://cdn.jsdelivr.net/npm/three@${THREE_VERSION}/build/three.module.js`;
const PREFIX = 'smash/'; // bare-specifier namespace used inside the bundle

// ── collect modules ──────────────────────────────────────────────────────────
function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (name.endsWith('.js')) out.push(p);
  }
  return out;
}
const files = walk(join(root, 'js')).sort();
const keyOf = (file) => PREFIX + relative(root, file).split('\\').join('/');

/** Rewrite relative import specifiers to bare ones that the import map resolves. */
function rewrite(file, src) {
  const dir = posix.dirname(relative(root, file).split('\\').join('/'));
  return src.replace(/((?:from\s*|import\s*\(?\s*)['"])(\.{1,2}\/[^'"]+)(['"])/g, (m, pre, spec, post) =>
    `${pre}${PREFIX}${posix.normalize(posix.join(dir, spec))}${post}`);
}
const dataUrl = (js) => 'data:text/javascript;base64,' + Buffer.from(js, 'utf8').toString('base64');

const imports = {};
let total = 0;
for (const file of files) {
  const src = rewrite(file, readFileSync(file, 'utf8'));
  imports[keyOf(file)] = dataUrl(src);
  total += src.length;
}

// ── three.js ─────────────────────────────────────────────────────────────────
if (online) {
  imports.three = THREE_CDN;
} else {
  const vendorDir = join(root, 'dist', 'vendor');
  const vendorFile = join(vendorDir, `three-${THREE_VERSION}.module.js`);
  if (!existsSync(vendorFile)) {
    mkdirSync(vendorDir, { recursive: true });
    console.log(`downloading ${THREE_CDN}`);
    const res = await fetch(THREE_CDN);
    if (!res.ok) throw new Error(`three download failed: ${res.status}`);
    writeFileSync(vendorFile, await res.text());
  }
  imports.three = dataUrl(readFileSync(vendorFile, 'utf8'));
}

// ── assemble the page ────────────────────────────────────────────────────────
let html = readFileSync(join(root, 'index.html'), 'utf8');
const css = readFileSync(join(root, 'style.css'), 'utf8');
const stamp = (readFileSync(join(root, 'js', 'config.js'), 'utf8').match(/build:\s*'([^']+)'/) || [])[1] || 'dev';

const replaceOnce = (needleRe, replacement, what) => {
  if (!needleRe.test(html)) throw new Error(`index.html: could not find ${what}`);
  html = html.replace(needleRe, replacement);
};
replaceOnce(/<link rel="stylesheet" href="style.css">/, () => `<style>\n${css}\n</style>`, 'stylesheet link');
replaceOnce(/<script type="importmap">[\s\S]*?<\/script>/, () =>
  `<script type="importmap">\n${JSON.stringify({ imports })}\n</script>`, 'import map');
replaceOnce(/<script type="module" src="js\/main.js"><\/script>/, () =>
  `<script type="module">import '${PREFIX}js/main.js';</script>`, 'main module script');
html = html.replace('<title>Smash Overdrive</title>', `<title>Smash Overdrive</title>\n  <!-- single-file build ${stamp}; generated by build.mjs, do not edit -->`);

mkdirSync(join(root, 'dist'), { recursive: true });
const out = join(root, 'dist', 'SmashOverdrive.html');
writeFileSync(out, html);
console.log(`${files.length} modules (${(total / 1024).toFixed(0)} KB of source) → ${relative(root, out)} (${(statSync(out).size / 1024 / 1024).toFixed(2)} MB, build ${stamp}, three ${online ? 'from CDN' : 'embedded'})`);

// ── static website variant ───────────────────────────────────────────────────
const webDir = join(root, 'dist', 'web');
for (const file of files) {
  const rel = relative(root, file);
  const dest = join(webDir, rel);
  mkdirSync(dirname(dest), { recursive: true });
  writeFileSync(dest, readFileSync(file, 'utf8').replace(/from\s+'three'/g, `from '${THREE_CDN}'`));
}
let web = readFileSync(join(root, 'index.html'), 'utf8');
web = web.replace(/<link rel="stylesheet" href="style.css">/, () => `<style>\n${css}\n</style>`);
web = web.replace(/\s*<!-- The single external dependency[^\n]*\n\s*<script type="importmap">[\s\S]*?<\/script>/, '');
web = web.replace('<title>Smash Overdrive</title>', `<title>Smash Overdrive</title>\n  <!-- static-site build ${stamp}; generated by build.mjs, do not edit -->`);
writeFileSync(join(webDir, 'index.html'), web);
console.log(`static site → ${relative(root, webDir)}/ (index.html + js/, three from CDN)`);
